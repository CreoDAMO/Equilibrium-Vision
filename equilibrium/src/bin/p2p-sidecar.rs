// ── Equilibrium P2P Sidecar ────────────────────────────────────────────────────
//
// Bridges the TypeScript node's simulated gossip to a real libp2p network.
// Extended with three capabilities beyond the original Gossipsub-only design:
//
//   1. mDNS local discovery — phones on the same WiFi find each other with
//      zero configuration and no seed peers.
//
//   2. Request-Response light-node protocol — any peer can query another for
//      chain headers and SMT state proofs directly over libp2p, with no HTTP
//      server required. This is the final piece that makes the mobile node
//      truly server-free: proofs flow over the P2P mesh, not over REST APIs.
//
//   3. Correlation IDs on all responses — the TS bridge can issue concurrent
//      commands without FIFO ordering assumptions.
//
// Protocol (stdin/stdout newline-delimited JSON):
//
//   Inbound commands (TS → sidecar):
//     {"id":"<uuid>","method":"gossip_block","blockHash":"<hex64>"}
//     {"id":"<uuid>","method":"gossip_tx","txHash":"<hex64>"}
//     {"id":"<uuid>","method":"peers"}
//     {"id":"<uuid>","method":"connect","addr":"<multiaddr>"}
//     {"id":"<uuid>","method":"listen_addrs"}
//     {"id":"<uuid>","method":"query_peer","peerId":"<peerid>","query":{...}}
//     {"id":"<uuid>","method":"lightnode_response","requestId":"<id>","ok":true,"data":{...}}
//
//   Outbound responses (sidecar → TS, all carry the original "id"):
//     {"id":"<uuid>","ok":true}
//     {"id":"<uuid>","ok":true,"peers":[...]}
//     {"id":"<uuid>","ok":true,"addrs":[...]}
//     {"id":"<uuid>","ok":true,"data":{...}}     ← light-node query response
//     {"id":"<uuid>","ok":false,"error":"..."}
//
//   Unsolicited events (no "id"):
//     {"event":"block","blockHash":"<hex64>","peerId":"..."}
//     {"event":"tx","txHash":"<hex64>","peerId":"..."}
//     {"event":"peer_connected","peerId":"..."}
//     {"event":"peer_disconnected","peerId":"..."}
//     {"event":"peer_discovered","peerId":"...","addrs":["<multiaddr>",...]}
//     {"event":"lightnode_request","requestId":"<uuid>","fromPeerId":"...","query":{...}}
//
// Build:   cargo build --release --bin p2p-sidecar  (from equilibrium/)
// Config:  P2P_PORT (default 9000), P2P_BOOTSTRAP (comma-separated multiaddrs)
//
// All log output goes to stderr so it never pollutes the JSON stdout stream.

use std::collections::{HashMap, HashSet};
use std::io::{BufRead, Write};
use std::str::FromStr;

use libp2p::{
    gossipsub, mdns, noise, request_response,
    swarm::{Config as SwarmConfig, NetworkBehaviour, SwarmEvent},
    tcp, yamux,
    core::upgrade::Version,
    identity, Multiaddr, PeerId, StreamProtocol, Transport,
};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use tokio::sync::mpsc;

// ── Topics ─────────────────────────────────────────────────────────────────────

const TOPIC_BLOCKS: &str = "equilibrium/blocks/1.0.0";
const TOPIC_TXS:    &str = "equilibrium/txs/1.0.0";
const LIGHTNODE_PROTO: &str = "/equilibrium/lightnode/1.0.0";

// ── Light-node request / response ──────────────────────────────────────────────

/// A light-node query sent from one peer to another over libp2p request-response.
#[derive(Serialize, Deserialize, Debug, Clone)]
struct LightnodeReq {
    /// Correlation ID generated by the originating TS node.
    id:     String,
    /// "tip" | "headers" | "sync" | "proof_account" | "proof_utxo"
    kind:   String,
    #[serde(default)]
    params: Value,
}

/// Response from the serving peer.
#[derive(Serialize, Deserialize, Debug, Clone)]
struct LightnodeResp {
    id:    String,
    ok:    bool,
    #[serde(skip_serializing_if = "Option::is_none")]
    data:  Option<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    error: Option<String>,
}

// ── Combined NetworkBehaviour ──────────────────────────────────────────────────

#[derive(NetworkBehaviour)]
struct Behaviour {
    gossipsub: gossipsub::Behaviour,
    mdns:      mdns::tokio::Behaviour,
    lightnode: request_response::json::Behaviour<LightnodeReq, LightnodeResp>,
}

// ── Command shape from TS ──────────────────────────────────────────────────────

#[derive(Deserialize)]
struct Command {
    /// Correlation ID — echoed in the response so the TS bridge can match it.
    #[serde(default)]
    id:         String,
    method:     String,
    #[serde(rename = "blockHash")]
    block_hash: Option<String>,
    #[serde(rename = "txHash")]
    tx_hash:    Option<String>,
    addr:       Option<String>,
    /// For query_peer: target peer's PeerId string.
    #[serde(rename = "peerId")]
    peer_id:    Option<String>,
    /// For query_peer: the query payload forwarded to the remote peer.
    query:      Option<Value>,
    /// For lightnode_response: the requestId from the inbound event.
    #[serde(rename = "requestId")]
    request_id: Option<String>,
    ok:         Option<bool>,
    data:       Option<Value>,
    error:      Option<String>,
}

// ── Pending state ──────────────────────────────────────────────────────────────

/// Maps a libp2p OutboundRequestId → the TS correlation ID, so when the
/// response arrives we can route it back to the right promise.
type OutboundMap = HashMap<request_response::OutboundRequestId, String>;

/// Maps a TS requestId (generated here for inbound requests) → the libp2p
/// ResponseChannel, so when the TS node calls lightnode_response we can
/// send the reply through the right libp2p channel.
type InboundMap = HashMap<String, request_response::ResponseChannel<LightnodeResp>>;

// ── Helpers ────────────────────────────────────────────────────────────────────

fn ok_resp(id: &str) -> Value {
    serde_json::json!({ "id": id, "ok": true })
}
fn err_resp(id: &str, msg: impl std::fmt::Display) -> Value {
    serde_json::json!({ "id": id, "ok": false, "error": msg.to_string() })
}

fn emit(stdout: &std::io::Stdout, val: &Value) {
    let mut out = stdout.lock();
    let _ = writeln!(out, "{}", serde_json::to_string(val).unwrap_or_default());
    let _ = out.flush();
}

// ── Main ───────────────────────────────────────────────────────────────────────

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let port: u16 = std::env::var("P2P_PORT")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(9000);

    let bootstrap_peers: Vec<String> = std::env::var("P2P_BOOTSTRAP")
        .unwrap_or_default()
        .split(',')
        .filter(|s| !s.trim().is_empty())
        .map(String::from)
        .collect();

    // ── Identity ───────────────────────────────────────────────────────────────
    let id_keys = identity::Keypair::generate_ed25519();
    let local_peer_id = PeerId::from(id_keys.public());
    eprintln!("[p2p-sidecar] peer_id={local_peer_id}");

    // ── Transport: TCP + Noise + Yamux ─────────────────────────────────────────
    let transport = tcp::tokio::Transport::default()
        .upgrade(Version::V1)
        .authenticate(noise::Config::new(&id_keys)?)
        .multiplex(yamux::Config::default())
        .boxed();

    // ── Gossipsub ──────────────────────────────────────────────────────────────
    let gossipsub_cfg = gossipsub::ConfigBuilder::default()
        .heartbeat_interval(std::time::Duration::from_secs(1))
        .validation_mode(gossipsub::ValidationMode::Strict)
        .build()
        .expect("valid gossipsub config");

    let mut gossipsub_beh = gossipsub::Behaviour::new(
        gossipsub::MessageAuthenticity::Signed(id_keys.clone()),
        gossipsub_cfg,
    )?;

    let topic_blocks = gossipsub::IdentTopic::new(TOPIC_BLOCKS);
    let topic_txs    = gossipsub::IdentTopic::new(TOPIC_TXS);
    gossipsub_beh.subscribe(&topic_blocks)?;
    gossipsub_beh.subscribe(&topic_txs)?;

    // ── mDNS — zero-config LAN peer discovery ─────────────────────────────────
    let mdns_beh = mdns::tokio::Behaviour::new(mdns::Config::default(), local_peer_id)?;

    // ── Request-Response light-node protocol ───────────────────────────────────
    let lightnode_beh = request_response::json::Behaviour::<LightnodeReq, LightnodeResp>::new(
        [(
            StreamProtocol::new(LIGHTNODE_PROTO),
            request_response::ProtocolSupport::Full,
        )],
        request_response::Config::default(),
    );

    // ── Combine into a single swarm behaviour ──────────────────────────────────
    let behaviour = Behaviour {
        gossipsub: gossipsub_beh,
        mdns:      mdns_beh,
        lightnode: lightnode_beh,
    };

    let mut swarm = libp2p::Swarm::new(
        transport,
        behaviour,
        local_peer_id,
        SwarmConfig::with_tokio_executor(),
    );

    // ── Listen ─────────────────────────────────────────────────────────────────
    let listen_addr: Multiaddr = format!("/ip4/0.0.0.0/tcp/{port}").parse()?;
    swarm.listen_on(listen_addr)?;

    // ── Bootstrap dial ─────────────────────────────────────────────────────────
    for addr_str in &bootstrap_peers {
        if let Ok(ma) = Multiaddr::from_str(addr_str) {
            if let Err(e) = swarm.dial(ma.clone()) {
                eprintln!("[p2p-sidecar] dial {addr_str} failed: {e}");
            } else {
                eprintln!("[p2p-sidecar] dialing bootstrap {addr_str}");
            }
        }
    }

    // ── Stdin reader — blocking I/O in its own OS thread ──────────────────────
    let (cmd_tx, mut cmd_rx) = mpsc::channel::<String>(64);
    std::thread::spawn(move || {
        let stdin = std::io::stdin();
        for line in stdin.lock().lines() {
            match line {
                Ok(l) if !l.trim().is_empty() => {
                    if cmd_tx.blocking_send(l).is_err() { break; }
                }
                Ok(_) => {}
                Err(_) => break,
            }
        }
    });

    let stdout = std::io::stdout();
    let mut connected:       HashSet<PeerId> = HashSet::new();
    let mut pending_outbound: OutboundMap    = HashMap::new();
    let mut pending_inbound:  InboundMap     = HashMap::new();

    // ── Event loop ─────────────────────────────────────────────────────────────
    loop {
        tokio::select! {
            // ── Inbound command from TS ────────────────────────────────────────
            Some(line) = cmd_rx.recv() => {
                let resp = handle_command(
                    &line,
                    &mut swarm,
                    &topic_blocks,
                    &topic_txs,
                    &mut pending_outbound,
                    &mut pending_inbound,
                );
                emit(&stdout, &resp);
            }

            // ── libp2p swarm events ────────────────────────────────────────────
            event = swarm.select_next_some() => {
                match event {

                    // ── Gossipsub messages ─────────────────────────────────────
                    SwarmEvent::Behaviour(BehaviourEvent::Gossipsub(
                        gossipsub::Event::Message { propagation_source, message, .. }
                    )) => {
                        let topic   = message.topic.as_str().to_string();
                        let payload = std::str::from_utf8(&message.data)
                            .unwrap_or("").trim().to_string();
                        let peer_id = propagation_source.to_string();

                        let evt = if topic == TOPIC_BLOCKS {
                            serde_json::json!({
                                "event": "block",
                                "blockHash": payload,
                                "peerId": peer_id
                            })
                        } else {
                            serde_json::json!({
                                "event": "tx",
                                "txHash": payload,
                                "peerId": peer_id
                            })
                        };
                        emit(&stdout, &evt);
                    }

                    // ── mDNS peer discovery ────────────────────────────────────
                    SwarmEvent::Behaviour(BehaviourEvent::Mdns(
                        mdns::Event::Discovered(list)
                    )) => {
                        for (peer_id, addr) in list {
                            eprintln!("[p2p-sidecar] mDNS discovered {peer_id} @ {addr}");
                            // Auto-dial so we form a mesh on the local network
                            let _ = swarm.dial(addr.clone());
                            let evt = serde_json::json!({
                                "event":  "peer_discovered",
                                "peerId": peer_id.to_string(),
                                "addrs":  [addr.to_string()],
                            });
                            emit(&stdout, &evt);
                        }
                    }

                    SwarmEvent::Behaviour(BehaviourEvent::Mdns(
                        mdns::Event::Expired(list)
                    )) => {
                        for (peer_id, _addr) in list {
                            eprintln!("[p2p-sidecar] mDNS expired {peer_id}");
                        }
                    }

                    // ── Light-node request-response ────────────────────────────

                    // Inbound: a remote peer is asking us for light-node data
                    SwarmEvent::Behaviour(BehaviourEvent::Lightnode(
                        request_response::Event::Message {
                            peer,
                            connection_id: _,
                            message: request_response::Message::Request {
                                request_id, request, channel
                            },
                        }
                    )) => {
                        // Give the channel an ID so the TS side can respond to it
                        let req_uuid = uuid_v4();
                        pending_inbound.insert(req_uuid.clone(), channel);
                        let evt = serde_json::json!({
                            "event":      "lightnode_request",
                            "requestId":  req_uuid,
                            "fromPeerId": peer.to_string(),
                            "query": {
                                "kind":   request.kind,
                                "params": request.params,
                            },
                        });
                        emit(&stdout, &evt);
                        let _ = request_id; // suppress warning
                    }

                    // Outbound response received: route back to the waiting TS promise
                    SwarmEvent::Behaviour(BehaviourEvent::Lightnode(
                        request_response::Event::Message {
                            connection_id: _,
                            message: request_response::Message::Response {
                                request_id, response
                            },
                            ..
                        }
                    )) => {
                        if let Some(corr_id) = pending_outbound.remove(&request_id) {
                            let out = if response.ok {
                                serde_json::json!({
                                    "id":   corr_id,
                                    "ok":   true,
                                    "data": response.data,
                                })
                            } else {
                                serde_json::json!({
                                    "id":    corr_id,
                                    "ok":    false,
                                    "error": response.error.unwrap_or_default(),
                                })
                            };
                            emit(&stdout, &out);
                        }
                    }

                    // Outbound request failed (timeout, dial failure, etc.)
                    SwarmEvent::Behaviour(BehaviourEvent::Lightnode(
                        request_response::Event::OutboundFailure {
                            request_id, error, ..
                        }
                    )) => {
                        if let Some(corr_id) = pending_outbound.remove(&request_id) {
                            let out = err_resp(&corr_id, error);
                            emit(&stdout, &out);
                        }
                    }

                    // Inbound request failed (channel closed before we responded)
                    SwarmEvent::Behaviour(BehaviourEvent::Lightnode(
                        request_response::Event::InboundFailure { .. }
                    )) => {}

                    SwarmEvent::Behaviour(BehaviourEvent::Lightnode(
                        request_response::Event::ResponseSent { .. }
                    )) => {}

                    // ── Connection lifecycle ───────────────────────────────────
                    SwarmEvent::ConnectionEstablished { peer_id, .. } => {
                        connected.insert(peer_id);
                        let evt = serde_json::json!({
                            "event":  "peer_connected",
                            "peerId": peer_id.to_string()
                        });
                        emit(&stdout, &evt);
                        eprintln!("[p2p-sidecar] connected: {peer_id}");
                    }

                    SwarmEvent::ConnectionClosed { peer_id, .. } => {
                        connected.remove(&peer_id);
                        let evt = serde_json::json!({
                            "event":  "peer_disconnected",
                            "peerId": peer_id.to_string()
                        });
                        emit(&stdout, &evt);
                    }

                    SwarmEvent::NewListenAddr { address, .. } => {
                        eprintln!("[p2p-sidecar] listening on {address}");
                    }

                    _ => {}
                }
            }
        }
    }
}

// ── Command handler ────────────────────────────────────────────────────────────

fn handle_command(
    line:             &str,
    swarm:            &mut libp2p::Swarm<Behaviour>,
    topic_blocks:     &gossipsub::IdentTopic,
    topic_txs:        &gossipsub::IdentTopic,
    pending_outbound: &mut OutboundMap,
    pending_inbound:  &mut InboundMap,
) -> Value {
    let cmd: Command = match serde_json::from_str(line) {
        Ok(c) => c,
        Err(e) => return serde_json::json!({ "id": "", "ok": false, "error": format!("parse error: {e}") }),
    };
    let id = cmd.id.as_str();

    match cmd.method.as_str() {

        "gossip_block" => {
            let hash = cmd.block_hash.unwrap_or_default();
            match swarm.behaviour_mut().gossipsub.publish(topic_blocks.clone(), hash.as_bytes().to_vec()) {
                Ok(_)  => ok_resp(id),
                Err(e) => err_resp(id, e),
            }
        }

        "gossip_tx" => {
            let hash = cmd.tx_hash.unwrap_or_default();
            match swarm.behaviour_mut().gossipsub.publish(topic_txs.clone(), hash.as_bytes().to_vec()) {
                Ok(_)  => ok_resp(id),
                Err(e) => err_resp(id, e),
            }
        }

        "peers" => {
            let peers: Vec<Value> = swarm
                .behaviour()
                .gossipsub
                .all_peers()
                .map(|(pid, _)| serde_json::json!({ "peerId": pid.to_string() }))
                .collect();
            serde_json::json!({ "id": id, "ok": true, "peers": peers })
        }

        "connect" => {
            let addr_str = cmd.addr.unwrap_or_default();
            match Multiaddr::from_str(&addr_str) {
                Ok(ma) => match swarm.dial(ma) {
                    Ok(_)  => ok_resp(id),
                    Err(e) => err_resp(id, e),
                },
                Err(e) => err_resp(id, format!("invalid multiaddr: {e}")),
            }
        }

        "listen_addrs" => {
            let addrs: Vec<String> = swarm.listeners().map(|a| a.to_string()).collect();
            serde_json::json!({ "id": id, "ok": true, "addrs": addrs })
        }

        // ── Light-node query: TS asks us to query a remote peer ────────────────
        "query_peer" => {
            let peer_id_str = cmd.peer_id.unwrap_or_default();
            let query       = cmd.query.unwrap_or(Value::Null);

            let Ok(peer_id) = peer_id_str.parse::<PeerId>() else {
                return err_resp(id, format!("invalid PeerId: {peer_id_str}"));
            };

            let req = LightnodeReq {
                id:     id.to_string(),
                kind:   query.get("kind").and_then(|v| v.as_str()).unwrap_or("tip").to_string(),
                params: query.get("params").cloned().unwrap_or(Value::Null),
            };

            let outbound_id = swarm.behaviour_mut().lightnode.send_request(&peer_id, req);
            pending_outbound.insert(outbound_id, id.to_string());
            // Response will arrive as a SwarmEvent — don't reply now
            // Return a sentinel so the TS bridge knows the request was dispatched
            serde_json::json!({ "id": id, "ok": true, "pending": true })
        }

        // ── Light-node response: TS sends us data to forward to a waiting peer ─
        "lightnode_response" => {
            let req_id = cmd.request_id.unwrap_or_default();
            let Some(channel) = pending_inbound.remove(&req_id) else {
                return err_resp(id, format!("unknown requestId: {req_id}"));
            };
            let resp = LightnodeResp {
                id:    req_id.clone(),
                ok:    cmd.ok.unwrap_or(true),
                data:  cmd.data,
                error: cmd.error,
            };
            match swarm.behaviour_mut().lightnode.send_response(channel, resp) {
                Ok(_)  => ok_resp(id),
                Err(_) => err_resp(id, "channel closed before response could be sent"),
            }
        }

        other => err_resp(id, format!("unknown method: {other}")),
    }
}

// ── UUID v4 (no external crate) ────────────────────────────────────────────────

fn uuid_v4() -> String {
    static COUNTER: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let c = COUNTER.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let t = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    // Both t and c are u64 — XOR is valid. Mix for uniqueness within a process.
    let hi = t.wrapping_mul(6364136223846793005u64).wrapping_add(c);
    format!("{hi:016x}{c:016x}")
}

